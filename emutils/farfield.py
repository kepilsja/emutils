def aperture(x_data: Iterable, y_data: Iterable, threshold: Union[str, float]='esqr') -> Dict:
    '''
    thershold: str or float
        Threshold value used to calculate parameters. Use "e" for 1/e factor,
        "esqr" for 1/e^2 factor or float in range (0, 1).
     '''
    A_fit, x0_fit, sigma_fit = fit_gaussian(x_data, y_data)

    if isinstance(threshold, str) and threshold in ('e', 'esqr'):
        delta_x = np.sqrt(2) * sigma_fit if threshold=='e' else 2 * sigma_fit
    elif isinstance(threshold, float) and threshold > 0 and threshold < 1:
        delta_x = sigma_fit * np.sqrt(2*np.log(1/threshold))
    else:
        raise ValueError(f'Wrong value of thershold! (look at docstring)')

    x_left = x0_fit - delta_x
    x_right = x0_fit + delta_x

    return {
        'fit_params': {'A': A_fit, 'x0': x0_fit, 'sigma': sigma_fit},
        'threshold_points': (x_left, x_right),
        'FWHM': 2 * np.sqrt(2 * np.log(2)) * sigma_fit,
    }

def plot_projection(theta, r, data, **kwargs) -> Axes:
    '''Plots farfield projection (absolute value of complex) in the polar coordinates.'''
    if 'marker' not in kwargs:
        kwargs['marker'] = '.'
    _, ax = plt.subplots(subplot_kw={"projection":"polar"})
    ax.scatter(theta, r, c=abs(data), **kwargs)
    return ax